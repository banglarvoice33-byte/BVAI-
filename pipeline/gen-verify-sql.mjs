// Generates sql/02_verify.sql from the tested JS reference (pipeline/schedule.mjs)
// so the SQL assertions can never drift from the rules: node pipeline/gen-verify-sql.mjs
import { writeFileSync } from 'node:fs';
import { isArticleSlot, isVideoJobDue } from './schedule.mjs';

const times = ['05:59', '06:00', '06:13', '06:14', '06:56', '07:00', '07:10', '07:30', '12:30', '22:00',
  '23:00', '23:44', '23:58', '00:00', '00:01', '03:00', '05:00', '05:30'];
const day = '2026-11-27';
const lines = times.map((hm) => {
  const d = new Date(`${day}T${hm}:00+06:00`);
  const a = isArticleSlot(d) ? 1 : 0;
  const v = isVideoJobDue(d) ? 1 : 0;
  const ts = `'${day} ${hm}:00+06'::timestamptz`;
  return `  assert (select count(*) from public.pipeline_due_slots(${ts}) where kind = 'article') = ${a}, 'article at ${hm}';\n` +
         `  assert (select count(*) from public.pipeline_due_slots(${ts}) where kind = 'video') = ${v}, 'video job at ${hm}';`;
});

const sql = `-- 02_verify.sql  (GENERATED by pipeline/gen-verify-sql.mjs: do not edit by hand)
-- Run after 01_pipeline_schema.sql. Any failed assertion stops with the message shown.
do $$
declare
  v_articles integer;
  v_videos   integer;
  v_first    integer;
  v_second   integer;
begin
  -- point checks (expected values come from the tested JavaScript reference)
${lines.join('\n')}

  -- a whole Dhaka day: 83 article slots and 12 video jobs
  select count(*) filter (where d.kind = 'article'), count(*) filter (where d.kind = 'video')
    into v_articles, v_videos
  from generate_series('${day} 00:00:00+06'::timestamptz, '${day} 23:59:00+06'::timestamptz, interval '1 minute') g(t)
  cross join lateral public.pipeline_due_slots(g.t) d;
  assert v_articles = 83, format('expected 83 article slots, got %s', v_articles);
  assert v_videos = 12, format('expected 12 video jobs, got %s', v_videos);

  -- idempotency: the same slot twice inserts once (uses a past date, cleaned up right after)
  v_first  := public.pipeline_tick('2026-01-05 06:14:00+06'::timestamptz);
  v_second := public.pipeline_tick('2026-01-05 06:14:00+06'::timestamptz);
  assert v_first = 1 and v_second = 0, format('tick idempotency failed: %s then %s', v_first, v_second);
  delete from public.pipeline_jobs where origin = 'schedule' and scheduled_for = '2026-01-05 06:14:00+06'::timestamptz;
end $$;

-- RLS must be ON for all four tables (rls_on = true)
select c.relname as table_name, c.relrowsecurity as rls_on
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relkind = 'r' and c.relname like 'pipeline\\_%'
order by 1;

-- anon/authenticated must not be able to call the scheduler functions (both rows false)
select 'anon can run pipeline_tick' as check_name,
       has_function_privilege('anon', 'public.pipeline_tick(timestamptz)', 'execute') as value
union all
select 'authenticated can run pipeline_tick',
       has_function_privilege('authenticated', 'public.pipeline_tick(timestamptz)', 'execute');
`;
writeFileSync(new URL('../sql/02_verify.sql', import.meta.url), sql);
console.log('wrote sql/02_verify.sql with', times.length, 'time points');
